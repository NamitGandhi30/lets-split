// Builds src/ui/doodles.generated.ts from the approved generator in design/assets/make-doodles.mjs.
import { writeFileSync } from "node:fs";
import { doodles } from "../../../design/assets/make-doodles.mjs";

const svg = Object.fromEntries(
  Object.entries(doodles).map(([k, f]) => [
    k,
    `<svg viewBox="0 0 100 100" xmlns="http://www.w3.org/2000/svg" aria-hidden="true"><rect width="100" height="100" fill="#FFF7EC"/>${f().replace(/\n/g, "")}</svg>`,
  ]),
);
const out = `// Generated by scripts/gen-doodles.mjs from design/assets/make-doodles.mjs. Do not edit.
export const DOODLES = ${JSON.stringify(svg, null, 2)} as const;
export type DoodleKey = keyof typeof DOODLES;
export const DOODLE_KEYS = Object.keys(DOODLES) as DoodleKey[];
`;
writeFileSync(new URL("../src/ui/doodles.generated.ts", import.meta.url), out);
console.log("doodles:", Object.keys(svg).join(", "));
